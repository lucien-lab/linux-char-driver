/*
 * sensor_calc.h - 纯逻辑计算函数（驱动与 KUnit 单元测试共用）
 *
 * ============================ 为什么要单独拆一个头文件 ============================
 * 驱动里有三类代码：
 *   1. 内核交互（regmap / 中断 / 文件操作）—— 只能在真实内核里测；
 *   2. 纯计算（寄存器原始值换算、参数合法性、环形下标推进）—— 与硬件无关；
 *   3. 策略（何时挂起、何时丢样本）。
 * 第 2 类最适合用内核单元测试（KUnit）覆盖：它们没有副作用、边界清晰，
 * 而恰恰是"最容易写错、错了又最难在真机上发现"的地方（例如负温度补码、下标回绕）。
 *
 * 拆成 static inline 而不是单独一个 .c：
 *   * 对驱动零额外开销（编译器内联，不引入跨编译单元的调用与符号）；
 *   * 不需要为一个函数多编译一个模块，也就不需要额外维护 EXPORT_SYMBOL 与模块依赖；
 *   * 同一份实现被 driver 与 sensor_kunit.ko 同时 include —— 测试测的就是驱动实际执行的代码，
 *     不存在"测试一份、跑另一份"的漂移（这是单元测试有意义的前提）。
 *
 * 约束：这里只能放**不依赖内核子系统、无副作用**的函数。一旦某个函数需要睡眠、
 * 需要锁、或需要访问设备寄存器，它就不属于这个头文件。
 * ================================================================================
 */
#ifndef _SENSOR_CALC_H
#define _SENSOR_CALC_H

#include <linux/types.h>
#include <linux/stddef.h>

/* ---------------------------------------------------------------------------
 * 温度寄存器换算
 *
 * 芯片约定（与 virt_i2c.c 文件头的寄存器图一致）：
 *   * 寄存器 16 位，但温度有效位是低 12 位（真实 TMP105 把 12 位数据放高 12 位、
 *     低 4 位是状态位；本项目为与既有代码保持一致，采用"低 12 位有效"的简化约定）；
 *   * 数值是二进制补码，LSB = 1/16 ℃ = 62.5 m℃；
 *   * 因此负温度必须**先从 12 位符号位扩展**，再乘。直接拿 u16 做算术会把
 *     -0.0625 ℃（0x0FFF）算成 +255.9 ℃ —— 这是这类驱动最经典的错误。
 * ------------------------------------------------------------------------- */
#define SENSOR_RAW_BITS		12
#define SENSOR_RAW_MASK		((1u << SENSOR_RAW_BITS) - 1u)	/* 0x0FFF */
#define SENSOR_RAW_SIGN_BIT	(1u << (SENSOR_RAW_BITS - 1))	/* 0x0800 */

/**
 * sensor_raw_to_milli - 12 位补码寄存器值 -> 毫摄氏度
 * @raw: 寄存器读回的 16 位原始值（只用低 12 位）
 *
 * 返回值单位是毫摄氏度（25.3125 ℃ -> 25312），与 ioctl/IIO 的约定一致。
 * 注意整数除法是向零截断：-0.0625 ℃ 得到 -62 m℃ 而不是 -63（真实硬件上
 * 用户态应当用 scale/offset 而不是靠驱动四舍五入，这里保持与既有行为一致）。
 */
static inline s32 sensor_raw_to_milli(u16 raw)
{
	u32 v = (u32)raw & SENSOR_RAW_MASK;
	s32 signed_raw = (v & SENSOR_RAW_SIGN_BIT)
			 ? (s32)v - (s32)(SENSOR_RAW_MASK + 1u)	/* 12 位补码 -> 负数 */
			 : (s32)v;

	return signed_raw * 1000 / 16;
}

/* ---------------------------------------------------------------------------
 * 采样周期合法性
 *
 * 两个入口共用（ioctl SENSOR_IOC_SET_INTERVAL 与 sysfs interval_ms）。
 * 判定只写一份，避免"同一个设置走 A 接口成功、走 B 接口失败"这种最难查的不一致
 * （本项目阶段 04 之前两个入口的下限分别是 10ms 与 1ms）。
 * ------------------------------------------------------------------------- */
#define SENSOR_INTERVAL_MIN_MS	1UL
#define SENSOR_INTERVAL_MAX_MS	60000UL

/**
 * sensor_interval_valid - 采样周期（毫秒）是否在允许范围内
 */
static inline bool sensor_interval_valid(unsigned long ms)
{
	return ms >= SENSOR_INTERVAL_MIN_MS && ms <= SENSOR_INTERVAL_MAX_MS;
}

/* ---------------------------------------------------------------------------
 * 环形下标推进
 *
 * 共享区（struct sensor_shm）里的 samples[] 是环形数组，写指针必须回绕。
 * 用独立函数表达有两个好处：一处实现避免多处写错；KUnit 可以直接测回绕边界
 * （cap-1 -> 0）—— 这类 off-by-one 在真机上表现为"数据偶尔错位一个样本"，
 * 极难复现。
 * ------------------------------------------------------------------------- */
/**
 * sensor_fifo_next - 环形缓冲下一个写位置
 * @idx: 当前下标
 * @cap: 缓冲容量（样本个数）；为 0 时返回 0（防御除零）
 */
static inline u32 sensor_fifo_next(u32 idx, u32 cap)
{
	if (!cap)
		return 0;
	return (idx + 1u) % cap;
}

#endif /* _SENSOR_CALC_H */
